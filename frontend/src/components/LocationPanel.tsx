import type { AiExplanation, RiskAssessment } from '../types'
import { RISK_COLORS, riskLabel } from '../utils/riskColors'
import { RainfallEvidence } from './RainfallEvidence'

interface Props {
  assessment: RiskAssessment | null
  loading: boolean
  explanation: AiExplanation | null
  explainLoading: boolean
  question: string
  onQuestionChange: (question: string) => void
  onExplain: () => void
  onOpenSimulation: () => void
}

export function LocationPanel({
  assessment,
  loading,
  explanation,
  explainLoading,
  question,
  onQuestionChange,
  onExplain,
  onOpenSimulation,
}: Props) {
  if (loading) {
    return (
      <aside className="panel">
        <p className="loading-state" role="status">Loading location assessment…</p>
      </aside>
    )
  }

  if (!assessment) {
    return (
      <aside className="panel">
        <h2>Select a location</h2>
        <p className="muted">Click a marker on the map to view risk details.</p>
        <p className="demo-badge">DEMO DATA</p>
      </aside>
    )
  }

  const color = RISK_COLORS[assessment.riskLevel]
  const lakeMonitoring = assessment.riskDimensions?.glacialLakeMonitoring
  const componentLabels: Record<string, string> = {
    rainfall_score: 'Rainfall',
    river_score: 'River level',
    exposure_score: 'Downstream exposure',
    historical_score: 'Historical context',
    temperature_score: 'Temperature',
    heat_index_score: 'Heat index',
    duration_score: 'Heat duration',
  }
  const floodDimensions = [
    { label: 'Rainfall', dimension: assessment.riskDimensions?.rainfallRisk },
    { label: 'River', dimension: assessment.riskDimensions?.riverRisk },
    { label: 'Exposure', dimension: assessment.riskDimensions?.downstreamExposure },
  ]

  return (
    <aside className="panel" aria-busy={explainLoading}>
      {assessment.simulationActive && (
        <div className="sim-banner">SIMULATION MODE — not real observations</div>
      )}
      <div className="panel-kicker">
        <p className="demo-badge">{assessment.dataProvenance === 'LIVE' ? 'LIVE DATA' : 'DEMO DATA'}</p>
        <span className="scenario-label">{assessment.scenario === 'flood_glof' ? 'FLOOD RISK' : 'EXTREME HEAT'}</span>
      </div>
      <h2>{assessment.location.name}</h2>
      <p className="state-line">{assessment.location.state}</p>

      <div className="risk-header" style={{ '--risk-color': color } as React.CSSProperties}>
        <div>
          <span className="risk-label">HeatShield calculated risk</span>
          <strong className="risk-level">{riskLabel(assessment.riskLevel)}</strong>
        </div>
        <div className="score-wrap">
          <strong className="risk-score">{assessment.riskScore}</strong>
          <span className="score-scale">/ 100</span>
        </div>
      </div>

      {lakeMonitoring && (
        <div className="monitoring-status">
          <span>Glacial lake monitoring</span>
          <strong>{lakeMonitoring.status?.toUpperCase() ?? 'UNAVAILABLE'}</strong>
          <small>Monitoring status is not a GLOF forecast.</small>
        </div>
      )}

      {assessment.scenario === 'flood_glof' && (
        <div className="risk-dimensions" aria-label="Flood risk dimensions">
          {floodDimensions.map(({ label, dimension }) => (
            <div key={label}>
              <span>{label}</span>
              <strong>{dimension?.level?.toUpperCase() ?? 'UNAVAILABLE'}</strong>
            </div>
          ))}
        </div>
      )}

      <p className="risk-category">{assessment.riskCategory}</p>
      <RainfallEvidence locationId={assessment.location.id} />

      <section>
        <h3>Calculated score contributions</h3>
        <ul className="score-breakdown">
          {Object.entries(assessment.componentScores).map(([key, score]) => (
            <li key={key}>
              <span>
                {componentLabels[key] ?? key.replaceAll('_', ' ')}
                {assessment.contributingFactors.find((factor) => factor.id === key.replace('_score', ''))?.detail && (
                  <small className="factor-detail">
                    {assessment.contributingFactors.find((factor) => factor.id === key.replace('_score', ''))?.detail}
                  </small>
                )}
              </span>
              <strong>+{score.toFixed(1)}</strong>
            </li>
          ))}
        </ul>
        <p className="muted small">Values are generated by HeatShield's risk engine.</p>
      </section>

      <section>
        <h3>Evidence and data availability</h3>
        <ul className="obs-list">
          {assessment.observations.map((o) => (
            <li key={o.label}>
              <span className={`obs-kind kind-${o.kind}`}>
                {o.kind === 'unavailable'
                  ? 'UNAVAILABLE'
                  : o.kind === 'calculated'
                    ? 'CALCULATED'
                    : o.kind === 'historical'
                      ? 'HISTORICAL'
                    : assessment.dataProvenance === 'LIVE'
                      ? 'OBSERVED'
                      : assessment.simulationActive
                        ? 'SIMULATED'
                        : 'DEMO INPUT'}
              </span>
              <span><strong>{o.label}</strong><br />{o.value}</span>
            </li>
          ))}
        </ul>
      </section>

      {assessment.providerObservations && (
        <section className="source-list">
          <h3>Provider status</h3>
          {Object.entries(assessment.providerObservations).map(([key, provider]) => (
            <div className="source-row" key={key}>
              <div>
                <strong>{key === 'glacialLake' ? 'Glacial lake' : key}</strong>
                <span>{provider.source} · {provider.status}</span>
                <small>{provider.dataQuality}</small>
              </div>
              <time dateTime={provider.timestamp}>{new Date(provider.timestamp).toLocaleTimeString()}</time>
            </div>
          ))}
        </section>
      )}

      <section className="copilot-section">
        <h3>Climate Copilot</h3>
        <form className="copilot-form" onSubmit={(event) => { event.preventDefault(); onExplain() }}>
          <label htmlFor="copilot-question">Ask about this assessment</label>
          <textarea
            id="copilot-question"
            value={question}
            onChange={(event) => onQuestionChange(event.target.value)}
            maxLength={2000}
            rows={2}
            placeholder="Why is this location high risk?"
          />
          <button type="submit" className="btn primary" disabled={explainLoading || !question.trim()}>
            {explainLoading ? 'Analyzing supplied data…' : 'Ask HeatShield'}
          </button>
        </form>
        {explanation && (
          <div className="ai-block" aria-live="polite">
            <p className="ai-summary">{explanation.summary}</p>
            {(['observed', 'calculated', 'interpreted', 'recommended'] as const).map((key) => (
              explanation.sections[key]?.length ? (
                <div key={key}>
                  <h4>{key}</h4>
                  <ul>
                    {explanation.sections[key].map((line) => <li key={line}>{line}</li>)}
                  </ul>
                </div>
              ) : null
            ))}
            <p className="muted small">{explanation.disclaimer}</p>
          </div>
        )}
      </section>

      <section>
        <h3>Preparedness information</h3>
        <ul>
          {assessment.recommendedActions.map((a) => (
            <li key={a}>{a}</li>
          ))}
        </ul>
      </section>

      <div className="panel-actions">
        <button type="button" className="btn secondary" onClick={onOpenSimulation}>
          Open simulation controls
        </button>
      </div>
      <p className="muted small">Confidence: {(assessment.confidence * 100).toFixed(0)}% · {assessment.uncertainty}</p>
      <p className="muted small">Assessment updated {new Date(assessment.timestamp).toLocaleString()}</p>
    </aside>
  )
}
